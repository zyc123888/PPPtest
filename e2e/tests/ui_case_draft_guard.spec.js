const { test, expect } = require('@playwright/test')

test('UI 用例编辑器保护未保存草稿', async ({ page }) => {
  await page.goto('/login')
  await page.getByPlaceholder('请输入用户名').fill(process.env.E2E_ADMIN_USER || 'admin')
  await page.getByPlaceholder('请输入密码').fill(process.env.E2E_ADMIN_PASSWORD || '')
  await page.getByRole('button', { name: '登录' }).click()
  await page.waitForURL(/\/dashboard/)

  await page.goto('/case/ui')
  await page.getByRole('button', { name: '高级创建' }).click()
  const editor = page.locator('.el-dialog:visible').filter({ hasText: '新增 UI 用例' })
  await expect(editor).toBeVisible()
  await editor.getByRole('tab', { name: /操作步骤/ }).click()
  await editor.getByRole('button', { name: '添加步骤' }).click()
  await editor.getByRole('button', { name: '删除步骤' }).click()
  await expect(editor.getByRole('status')).toContainText('步骤已删除')
  await editor.getByRole('button', { name: '撤销' }).click()
  await expect(editor.getByRole('button', { name: '删除步骤' })).toHaveCount(1)
  await editor.getByRole('tab', { name: '基本信息' }).click()
  const name = editor.locator('.el-form-item').filter({ hasText: '用例名称' }).locator('input')
  await name.fill('草稿保护验证')
  await page.keyboard.press('Escape')
  const confirmation = page.locator('.el-message-box:visible')
  await expect(confirmation).toContainText('放弃未保存的修改')
  await confirmation.getByRole('button', { name: '继续编辑' }).click()
  await expect(name).toHaveValue('草稿保护验证')

  await editor.getByRole('button', { name: '取消', exact: true }).click()
  await confirmation.getByRole('button', { name: '放弃修改' }).click()
  await expect(editor).toBeHidden()

  await page.getByRole('button', { name: '高级创建' }).click()
  await expect(editor).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(editor).toBeHidden()
  await expect(confirmation).toHaveCount(0)
})
